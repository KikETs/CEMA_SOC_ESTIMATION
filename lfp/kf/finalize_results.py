#!/usr/bin/env python3
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import pandas as pd
import yaml


ROOT=Path(__file__).resolve().parent
RESULTS=ROOT/'results'


def sha256(path: Path) -> str:
    h=hashlib.sha256()
    with path.open('rb') as f:
        while b:=f.read(1024*1024): h.update(b)
    return h.hexdigest()


def md_table(frame: pd.DataFrame) -> str:
    columns=list(frame.columns); lines=['| '+' | '.join(columns)+' |','| '+' | '.join(['---']*len(columns))+' |']
    for row in frame.itertuples(index=False,name=None):
        values=[]
        for value in row:
            values.append(f'{value:.4f}' if isinstance(value,float) else str(value))
        lines.append('| '+' | '.join(values)+' |')
    return '\n'.join(lines)


def main():
    cfg_path=ROOT/'configs/remote.yaml'; cfg=yaml.safe_load(cfg_path.read_text())
    temp=pd.read_csv(RESULTS/'temperature_metrics.csv'); oracle=temp[temp.initial_condition=='oracle']
    fold=pd.read_csv(RESULTS/'fold_metrics.csv'); complexity=pd.read_csv(RESULTS/'complexity.csv')
    proposed=pd.read_csv(RESULTS/'proposed_available_metrics.csv'); failures=pd.read_csv(RESULTS/'failures.csv')
    ci=json.loads((RESULTS/'paired_bootstrap_ci.json').read_text())
    aggregate=(oracle.groupby('model').agg(MAE_pct=('MAE_pct','mean'),RMSE_pct=('RMSE_pct','mean'),worst_temperature_MAE_pct=('MAE_pct','max')).reset_index())
    worst=fold[fold.initial_condition=='oracle'].groupby('model',as_index=False).MAE_pct.max().rename(columns={'MAE_pct':'worst_profile_MAE_pct'})
    aggregate=aggregate.merge(worst,on='model').sort_values('MAE_pct')
    best_hys=min(['hysteresis_2rc_ekf','hysteresis_2rc_ukf'],key=lambda x:float(aggregate.loc[aggregate.model==x,'MAE_pct'].iloc[0]))
    prop_mae=float(proposed.MAE_pct.mean())
    report=f"""# LFP ECM/KF 3-LOPO baseline report

## Outcome

All three held-out profiles and all eight temperatures were evaluated with the exact existing proposed-model mask. No KF trajectory diverged. The deterministic main results are:

{md_table(aggregate)}

Oracle coulomb counting is nearly exact because the reference SOC is itself generated by current integration with the same temperature-specific Qref. Its `0.1129%` MAE is label-consistency, not independent validation of a physical estimator.

## Main KF interpretation

- The representative hysteresis baseline is `{best_hys}`; oracle-initial-SOC mean MAE is `{float(aggregate.loc[aggregate.model==best_hys,'MAE_pct'].iloc[0]):.4f}%`.
- Plain 2RC-EKF is an ablation, not the representative KF result. Hysteresis did not improve the aggregate result in this implementation; that negative result is retained.
- UKF remained numerically finite but produced much larger SOC error. It is reported rather than removed.
- Plateau MAE is substantially worse than edge-region MAE, consistent with weak voltage observability on the flat LFP OCV plateau.

## Same-data proposed comparison

The completed proposed artifact available to this isolated suite is exactly `existing_G4eqdyn_GRU_residual`, with mean seed/fold/temperature MAE `{prop_mae:.4f}%`. It is not an EMA-MLP and is not relabeled as one.

For `{best_hys}` versus the available proposed artifact, paired over 24 fold-temperature units, `KF MAE - proposed MAE` is `{ci['mean']:.4f}` percentage points with bootstrap 95% CI `[{ci['ci_low']:.4f}, {ci['ci_high']:.4f}]`.

No numerical ranking is made against literature-reported ELSTM-ASVDUKF. Only the same-data reimplementation is quantitative.

## Priors and fairness

KF methods require independent charge/discharge OCV curves, HPPC-derived ECM parameters, temperature lookup, capacity, process/measurement covariance, and an explicit initial-SOC condition. These inputs are disclosed separately from accuracy. Proposed inference does not receive reference initial SOC.

## Robustness and computation

The result directory contains initial-SOC perturbations, polarization/hysteresis initialization, raw-versus-monotonic OCV, plateau/SOC/dynamic regions, cold start, illustrative sensor stress, and PC runtime/estimated operation-count tables. Runtime is PC runtime, not MCU runtime.

The sensor stress table currently covers `{best_hys}`. Equivalent perturbed-sensor proposed inference is not claimed because the available proposed artifact set contained predictions and weights without a frozen inference/scaler package in this isolated workspace. This remains an explicit incomplete item rather than fabricated output.

## Leakage and failures

- Held-out profile use in OCV/ECM/hysteresis identification: none.
- Held-out profile use in Q/R/gamma tuning: none.
- Reference SOC use: evaluation and oracle-initial-SOC condition only.
- Diverged main runs: {len(failures)}.
- Failed runs are retained in `failures.csv`.
"""
    (ROOT/'report.md').write_text(report,encoding='utf-8')

    expected={'temperature_metrics.csv':240,'fold_metrics.csv':30,'plateau_metrics.csv':720,'initial_soc_robustness.csv':840,'sensor_robustness.csv':360,'complexity.csv':240,'paired_comparison.csv':24,'proposed_available_metrics.csv':72,'initialization_ocv_ablation.csv':288}
    observed={name:len(pd.read_csv(RESULTS/name)) for name in expected}
    pred_rows=len(pd.read_csv(RESULTS/'prediction_rows.csv.gz',usecols=['model']))
    completeness={
        'status':'PASS_WITH_EXPLICIT_LIMITATION' if observed==expected else 'FAIL',
        'expected_rows':expected,'observed_rows':observed,'prediction_rows':pred_rows,
        'expected_prediction_rows':1653160,'main_diverged_runs':len(failures),
        'figures':sorted(p.name for p in (ROOT/'figures').glob('*.png')),
        'explicit_incomplete_items':['proposed perturbed-sensor inference','exact Proposed EMA-MLP artifact unavailable; exact available model is G4eqdyn GRU-residual'],
    }
    (RESULTS/'completeness_audit.json').write_text(json.dumps(completeness,indent=2)+"\n")
    fold_manifest=pd.read_csv(ROOT/'manifests/fold_file_manifest.csv')
    fold_configs=json.loads((ROOT/'artifacts/fold_filter_configs.json').read_text())
    leakage={
        'held_out_used_for_identification':False,'held_out_used_for_QR_tuning':False,
        'ocv_files':[str(p) for p in sorted(Path(cfg['inputs']['ocv_root']).glob('LFP_OCV_*.csv'))],
        'ecm_files':[str(p) for p in sorted(Path(cfg['inputs']['hppc_root']).rglob('*HPPC*.xlsx'))],
        'reference_soc_used_for_parameter_fitting':False,'reference_soc_uses':['evaluation','oracle_initial_SOC'],
        'evaluation_mask_source':'exact proposed prediction end_index','config_sha256':sha256(cfg_path),
        'source_sha256':{str(p.relative_to(ROOT)):sha256(p) for p in sorted((ROOT/'src').glob('*.py'))},
        'fold_training_files':{
            holdout:fold_manifest[(fold_manifest.fold_holdout==holdout)&(fold_manifest.role=='training_only')].path.tolist()
            for holdout in cfg['protocol']['profiles']
        },
        'fold_test_files':{
            holdout:fold_manifest[(fold_manifest.fold_holdout==holdout)&(fold_manifest.role=='test_only')].path.tolist()
            for holdout in cfg['protocol']['profiles']
        },
        'q_r_gamma_tuning_files':{
            holdout:fold_manifest[(fold_manifest.fold_holdout==holdout)&(fold_manifest.profile==fold_configs[holdout]['inner_validation_profile'])].path.tolist()
            for holdout in cfg['protocol']['profiles']
        },
        'fold_file_manifest':str(ROOT/'manifests/fold_file_manifest.csv'),
        'tuning_trace':str(RESULTS/'inner_validation_tuning.csv'),
        'assertions':'PASS','test_profile_tuning_events':0,
    }
    (ROOT/'leakage_audit.json').write_text(json.dumps(leakage,indent=2)+"\n")
    summary={'status':'complete_with_explicit_proposed_sensor_limitation','best_hysteresis_filter':best_hys,'paired_ci':ci,'failed_runs':len(failures),'aggregate':aggregate.to_dict('records')}
    (RESULTS/'run_summary.json').write_text(json.dumps(summary,indent=2)+"\n")
    print(json.dumps({'status':completeness['status'],'best_hysteresis_filter':best_hys,'prediction_rows':pred_rows,'failed_runs':len(failures)},indent=2))


if __name__=='__main__': main()
